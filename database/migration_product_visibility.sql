-- ============================================================
-- Миграция: независимая видимость товаров
--
-- Применять один раз после резервного копирования базы данных.
-- Существующие товары остаются видимыми.
-- ============================================================
ALTER TABLE products
    ADD COLUMN is_visible TINYINT(1) NOT NULL DEFAULT 1
        COMMENT '1 = товар показывается на сайте, 0 = скрыт'
        AFTER status,
    ADD KEY idx_products_is_visible (is_visible);
